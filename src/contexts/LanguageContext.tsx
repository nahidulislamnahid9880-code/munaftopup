interface LanguageContextValue {
  lang: StoreLanguage;
  setLang: (lang: StoreLanguage) => void;
  toggleLang: () => void;
  t: (key: string, fallback?: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({children}: {children: React.ReactNode}) {
  const [lang, setLangState] = useState<StoreLanguage>(() => {
    try {
      const saved = localStorage.getItem(LANG_STORAGE_KEY);
      return saved === 'bn' ? 'bn' : 'en';
    } catch {
      return 'en';
    }
  });

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem(LANG_STORAGE_KEY, lang);
    } catch {
      // ignore storage failure
    }
  }, [lang]);

  const setLang = (next: StoreLanguage) => setLangState(next);
  const toggleLang = () => setLangState((prev) => (prev === 'en' ? 'bn' : 'en'));
  const t = (key: string, fallback?: string) =>
    TRANSLATIONS[lang][key] ?? TRANSLATIONS.en[key] ?? fallback ?? key;

  return (
    <LanguageContext.Provider value={{lang, setLang, toggleLang, t}}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage(): LanguageContextValue {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used inside LanguageProvider');
  return ctx;
}
